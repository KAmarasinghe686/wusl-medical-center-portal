-- RLS Policies
create policy "Students can view and create their own advance notices"
  on public.advance_medical_notices
  for all
  using (
    exists (
      select 1 from public.students s
      where s.student_id = advance_medical_notices.student_id
        and s.user_id = auth.uid()
    )
  )
  with check (
    exists (
      select 1 from public.students s
      where s.student_id = advance_medical_notices.student_id
        and s.user_id = auth.uid()
    )
  );

create policy "Faculty and Dean and Admin can view all advance notices"
  on public.advance_medical_notices
  for select
  using (
    exists (
      select 1 from public.profiles p
      where p.id = auth.uid()
        and p.role in ('faculty', 'dean', 'admin', 'doctor')
    )
  );

create policy "Faculty and Dean and Admin can update advance notices"
  on public.advance_medical_notices
  for update
  using (
    exists (
