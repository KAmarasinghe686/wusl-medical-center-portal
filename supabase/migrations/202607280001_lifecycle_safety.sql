create table if not exists public.medical_record_lifecycle_history (
  history_id bigint generated by default as identity primary key,
  record_id bigint not null references public.medical_records(record_id) on delete restrict,
  previous_status text not null check (previous_status in ('active', 'archived', 'invalidated')),
  new_status text not null check (new_status in ('active', 'archived', 'invalidated')),
  reason text not null,
  changed_by uuid not null,
  changed_at timestamptz not null default now()
