-- Administrator-controlled batch onboarding with per-row retry history.

do $$
begin
  if not exists (
    select 1
    from pg_constraint
    where conrelid = 'public.students'::regclass
      and conname = 'students_applied_science_index_check'
  ) then
    alter table public.students
      add constraint students_applied_science_index_check
      check (index_no ~ '^2[0-9]2[0-9]{3}$') not valid;
  end if;
end;
$$;

create table if not exists public.onboarding_imports (
  job_id uuid primary key default gen_random_uuid(),
  import_type text not null check (import_type in ('students', 'personnel')),
  source_file text,
  status text not null default 'processing'
    check (status in ('processing', 'completed', 'partial', 'failed')),
  total_rows integer not null default 0 check (total_rows >= 0),
  successful_rows integer not null default 0 check (successful_rows >= 0),
  failed_rows integer not null default 0 check (failed_rows >= 0),
  skipped_rows integer not null default 0 check (skipped_rows >= 0),
  created_by uuid not null references auth.users(id) on delete restrict,
  created_at timestamptz not null default now(),
  completed_at timestamptz
);

create table if not exists public.onboarding_import_rows (
  row_id bigint generated by default as identity primary key,
  job_id uuid not null references public.onboarding_imports(job_id) on delete cascade,
  row_number integer not null check (row_number > 0),
  email text not null,
  identifier text not null,
  payload jsonb not null,
  status text not null default 'pending'
    check (status in ('pending', 'invited', 'skipped', 'failed')),
  error_message text,
  auth_user_id uuid references auth.users(id) on delete set null,
  attempt_count integer not null default 0 check (attempt_count >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(job_id, row_number)
);

create index if not exists onboarding_imports_created_idx
  on public.onboarding_imports(created_at desc);
create index if not exists onboarding_import_rows_job_status_idx
  on public.onboarding_import_rows(job_id, status, row_number);

drop trigger if exists onboarding_import_rows_set_updated_at on public.onboarding_import_rows;
create trigger onboarding_import_rows_set_updated_at
  before update on public.onboarding_import_rows
  for each row execute function public.set_updated_at();

alter table public.onboarding_imports enable row level security;
alter table public.onboarding_import_rows enable row level security;

drop policy if exists onboarding_imports_admin_select on public.onboarding_imports;
create policy onboarding_imports_admin_select on public.onboarding_imports
  for select to authenticated
  using (public.current_user_role() = 'admin');

drop policy if exists onboarding_import_rows_admin_select on public.onboarding_import_rows;
create policy onboarding_import_rows_admin_select on public.onboarding_import_rows
  for select to authenticated
  using (public.current_user_role() = 'admin');

revoke all on public.onboarding_imports, public.onboarding_import_rows from anon;
revoke insert, update, delete on public.onboarding_imports, public.onboarding_import_rows from authenticated;
grant select on public.onboarding_imports, public.onboarding_import_rows to authenticated;
