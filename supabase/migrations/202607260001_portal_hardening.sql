create or replace function public.current_user_role()
returns text
language sql
stable
security definer
set search_path = public
as $$
  select role from public.profiles where id = auth.uid()
$$;

create or replace function public.current_student_id()
returns bigint
language sql
stable
security definer
set search_path = public
as $$
  select student_id
  from public.students
  where user_id = auth.uid()
    and public.current_user_role() = 'student'
$$;

create or replace function public.current_doctor_id()
returns bigint
language sql
stable
security definer
set search_path = public
as $$
  select doctor_id
  from public.doctors
  where user_id = auth.uid()
    and public.current_user_role() = 'doctor'
$$;

create or replace function public.can_view_medical_record(p_record_id bigint)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.medical_records mr
    where mr.record_id = p_record_id
      and (
        mr.student_id = public.current_student_id()
        or (
          public.current_user_role() = 'doctor'
          and (mr.status = 'pending' or mr.reviewed_by = public.current_doctor_id())
        )
        or (public.current_user_role() = 'faculty' and mr.status = 'approved')
        or public.current_user_role() = 'admin'
      )
  )
$$;

create or replace function public.can_view_medical_document(p_path text)
returns boolean
language sql
stable
security definer
set search_path = public, storage
as $$
  select exists (
    select 1
    from public.record_images ri
    where ri.file_path = p_path
      and public.can_view_medical_record(ri.record_id)
  )
$$;

create or replace function public.handle_new_auth_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, full_name, role)
  values (
    new.id,
    nullif(new.raw_user_meta_data ->> 'full_name', ''),
    case
      when new.raw_user_meta_data ->> 'role' in ('student', 'doctor', 'worker', 'faculty', 'admin')
        then new.raw_user_meta_data ->> 'role'
      else 'unassigned'
    end
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

