-- Backfill legacy records so leave duration defaults to issue_date
update public.medical_records
set leave_start_date = coalesce(leave_start_date, issue_date),
    leave_end_date = coalesce(leave_end_date, issue_date),
    leave_days_count = coalesce(leave_days_count, 1),
    number_of_holidays = coalesce(number_of_holidays, 0)
where leave_start_date is null or leave_end_date is null;

