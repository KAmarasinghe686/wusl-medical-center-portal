create or replace function public.current_user_active()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select coalesce(
    (select is_active from public.profiles where id = auth.uid()),
    false
  )
$$;

create or replace function public.current_user_role()
returns text
language sql
stable
security definer
set search_path = public
as $$
  select role
  from public.profiles
  where id = auth.uid()
    and is_active
$$;

create or replace function public.can_view_medical_record(p_record_id bigint)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.medical_records mr
    where mr.record_id = p_record_id
      and public.current_user_active()
      and (
        mr.student_id = public.current_student_id()
        or (
          mr.lifecycle_status = 'active'
          and public.current_user_role() = 'doctor'
          and (mr.status = 'pending' or mr.reviewed_by = public.current_doctor_id())
        )
        or (
          mr.lifecycle_status = 'active'
          and public.current_user_role() = 'faculty'
          and mr.status = 'approved'
        )
        or public.current_user_role() = 'admin'
      )
  )
$$;

create or replace function public.can_view_medical_document(p_path text)
returns boolean
language sql
stable
security definer
set search_path = public, storage
as $$
  select exists (
    select 1
    from public.record_images ri
    where ri.file_path = p_path
      and ri.disposal_status = 'retained'
      and public.can_view_medical_record(ri.record_id)
  )
$$;

create or replace function public.prevent_nonactive_record_review()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if old.lifecycle_status <> 'active'
     and (
       new.status is distinct from old.status
       or new.reviewed_by is distinct from old.reviewed_by
       or new.diagnosis is distinct from old.diagnosis
       or new.observation_notes is distinct from old.observation_notes
       or new.recommendation is distinct from old.recommendation
       or new.rejection_reason is distinct from old.rejection_reason
     ) then
    raise exception 'Archived or invalidated records cannot be reviewed' using errcode = '42501';
  end if;
  return new;
end;
$$;

drop trigger if exists prevent_nonactive_record_review on public.medical_records;
create trigger prevent_nonactive_record_review
  before update on public.medical_records
  for each row execute function public.prevent_nonactive_record_review();

create or replace function public.admin_set_account_status(
  p_actor_id uuid,
  p_user_id uuid,
  p_is_active boolean,
  p_reason text
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_previous boolean;
  v_target_role text;
  v_reason text := nullif(trim(p_reason), '');
begin
  if not exists (
    select 1 from public.profiles
    where id = p_actor_id and role = 'admin' and is_active
  ) then
    raise exception 'Only an active administrator can change account status' using errcode = '42501';
  end if;
  if v_reason is null then
    raise exception 'A status-change reason is required' using errcode = '22023';
  end if;
  if not p_is_active and p_actor_id = p_user_id then
    raise exception 'Administrators cannot deactivate their own account' using errcode = '42501';
  end if;

  select is_active, role into v_previous, v_target_role
  from public.profiles
  where id = p_user_id
  for update;
  if not found then
    raise exception 'Profile not found' using errcode = 'P0002';
  end if;
  if v_previous = p_is_active then
    return;
  end if;
  if not p_is_active and v_target_role = 'admin'
     and (select count(*) from public.profiles where role = 'admin' and is_active) <= 1 then
    raise exception 'The final active administrator cannot be deactivated' using errcode = '42501';
  end if;

  update public.profiles
  set is_active = p_is_active,
      status_reason = v_reason,
      status_changed_at = now(),
      status_changed_by = p_actor_id
  where id = p_user_id;

  if not p_is_active and v_target_role = 'doctor' then
    update public.doctor_availability da
    set is_available = false
    from public.doctors d
    where d.user_id = p_user_id
      and da.doctor_id = d.doctor_id;
  end if;

  insert into public.account_status_history(
    user_id, previous_status, new_status, reason, changed_by
  ) values (
    p_user_id,
    case when v_previous then 'active' else 'inactive' end,
    case when p_is_active then 'active' else 'inactive' end,
    v_reason,
    p_actor_id
  );

  insert into public.audit_logs(action, table_name, record_id, user_id, old_data, new_data)
  values (
    case when p_is_active then 'ACCOUNT_REACTIVATED' else 'ACCOUNT_DEACTIVATED' end,
    'profiles',
    p_user_id::text,
    p_actor_id,
    jsonb_build_object('is_active', v_previous),
    jsonb_build_object('is_active', p_is_active, 'reason', v_reason)
  );
end;
$$;

create or replace function public.admin_change_medical_record_lifecycle(
  p_actor_id uuid,
  p_record_id bigint,
  p_new_status text,
  p_reason text
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_record public.medical_records%rowtype;
  v_reason text := nullif(trim(p_reason), '');
  v_student_user uuid;
begin
  if not exists (
    select 1 from public.profiles
    where id = p_actor_id and role = 'admin' and is_active
  ) then
    raise exception 'Only an active administrator can change record lifecycle status' using errcode = '42501';
  end if;
  if p_new_status not in ('active', 'archived', 'invalidated') then
    raise exception 'Invalid lifecycle status' using errcode = '22023';
  end if;
  if v_reason is null then
    raise exception 'A lifecycle reason is required' using errcode = '22023';
  end if;

  select * into v_record
  from public.medical_records
  where record_id = p_record_id
  for update;
  if not found then
    raise exception 'Medical record not found' using errcode = 'P0002';
  end if;
  if v_record.lifecycle_status = p_new_status then
    return;
  end if;
  if p_new_status = 'archived'
     and v_record.status = 'pending'
     and v_record.lifecycle_status = 'active' then
    raise exception 'A pending medical record cannot be archived' using errcode = '22023';
  end if;

  update public.medical_records
  set lifecycle_status = p_new_status,
      lifecycle_reason = v_reason,
      lifecycle_changed_at = now(),
      lifecycle_changed_by = p_actor_id
  where record_id = p_record_id;

  insert into public.medical_record_lifecycle_history(
    record_id, previous_status, new_status, reason, changed_by
  ) values (
    p_record_id, v_record.lifecycle_status, p_new_status, v_reason, p_actor_id
  );

  insert into public.audit_logs(action, table_name, record_id, user_id, old_data, new_data)
  values (
    'RECORD_' || upper(p_new_status),
    'medical_records',
    p_record_id::text,
    p_actor_id,
    jsonb_build_object('lifecycle_status', v_record.lifecycle_status),
    jsonb_build_object('lifecycle_status', p_new_status, 'reason', v_reason)
  );

  select s.user_id into v_student_user
  from public.students s
  where s.student_id = v_record.student_id;
  if v_student_user is not null then
    insert into public.notifications(user_id, title, message, type)
    values (
      v_student_user,
      'Medical record ' || initcap(p_new_status),
      'Medical record REC-' || p_record_id || ' was ' || p_new_status || '. Reason: ' || v_reason,
      'record_' || p_new_status
    );
  end if;
end;
$$;

create or replace function public.void_medical_visit(
  p_actor_id uuid,
  p_visit_id bigint,
  p_reason text
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_doctor_id bigint;
  v_previous public.medical_visits%rowtype;
  v_updated public.medical_visits%rowtype;
  v_reason text := nullif(trim(p_reason), '');
begin
  select d.doctor_id into v_doctor_id
  from public.doctors d
  join public.profiles p on p.id = d.user_id
  where d.user_id = p_actor_id
    and p.role = 'doctor'
    and p.is_active;
  if v_doctor_id is null then
    raise exception 'Only an active doctor can void a visit' using errcode = '42501';
  end if;
  if v_reason is null or char_length(v_reason) < 5 then
    raise exception 'A clear void reason of at least 5 characters is required' using errcode = '22023';
  end if;

  select * into v_previous
  from public.medical_visits
  where visit_id = p_visit_id
    and doctor_id = v_doctor_id
  for update;
  if not found then
    raise exception 'Visit not found' using errcode = 'P0002';
  end if;
  if v_previous.status = 'voided' then
    raise exception 'This visit has already been voided' using errcode = '22023';
  end if;

  update public.medical_visits
  set status = 'voided',
      void_reason = v_reason,
      voided_at = now(),
      voided_by = p_actor_id,
      updated_at = now()
  where visit_id = p_visit_id
  returning * into v_updated;

  insert into public.audit_logs(action, table_name, record_id, user_id, old_data, new_data)
  values (
    'VISIT_VOIDED',
    'medical_visits',
    p_visit_id::text,
    p_actor_id,
    to_jsonb(v_previous),
    to_jsonb(v_updated)
  );
end;
$$;

-- Inactive users may read their own profile only so the login and proxy layers
-- can explain that access is disabled. Every other protected operation requires
-- current_user_active().
drop policy if exists profiles_select on public.profiles;
create policy profiles_select on public.profiles for select to authenticated
using (
  id = auth.uid()
  or (
    public.current_user_active()
    and (
      public.current_user_role() = 'admin'
      or (public.current_user_role() = 'doctor' and employee_index is not null)
    )
  )
);

drop policy if exists profiles_update_own on public.profiles;
create policy profiles_update_own on public.profiles for update to authenticated
using (public.current_user_active() and id = auth.uid())
with check (public.current_user_active() and id = auth.uid());

drop policy if exists students_select on public.students;
create policy students_select on public.students for select to authenticated
using (
  public.current_user_active()
  and (
    user_id = auth.uid()
    or public.current_user_role() in ('doctor', 'faculty', 'admin')
  )
);

drop policy if exists students_update_own on public.students;
create policy students_update_own on public.students for update to authenticated
using (public.current_user_active() and user_id = auth.uid())
with check (public.current_user_active() and user_id = auth.uid());

drop policy if exists doctors_select on public.doctors;
create policy doctors_select on public.doctors for select to authenticated
using (public.current_user_active());

drop policy if exists doctors_update_own on public.doctors;
create policy doctors_update_own on public.doctors for update to authenticated
using (public.current_user_active() and user_id = auth.uid())
with check (public.current_user_active() and user_id = auth.uid());

drop policy if exists doctor_availability_select on public.doctor_availability;
create policy doctor_availability_select on public.doctor_availability for select to authenticated
using (public.current_user_active());

drop policy if exists medical_visits_select on public.medical_visits;
create policy medical_visits_select on public.medical_visits for select to authenticated
using (
  public.current_user_active()
  and (
    user_id = auth.uid()
    or (public.current_user_role() = 'doctor' and doctor_id = public.current_doctor_id())
    or (public.current_user_role() = 'faculty' and patient_type = 'Student')
    or public.current_user_role() = 'admin'
  )
);

