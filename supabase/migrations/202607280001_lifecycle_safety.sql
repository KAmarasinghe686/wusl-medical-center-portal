-- Safe account, visit, record, and document lifecycle controls.
-- Apply to the hosted project with `npx supabase db push`.

alter table public.profiles
  add column if not exists is_active boolean not null default true,
  add column if not exists status_reason text,
  add column if not exists status_changed_at timestamptz,
  add column if not exists status_changed_by uuid references auth.users(id) on delete set null;

-- Preserve the status of Auth users that were already banned before this migration.
update public.profiles p
set is_active = false,
    status_reason = coalesce(p.status_reason, 'Account was already disabled in authentication.'),
    status_changed_at = coalesce(p.status_changed_at, now())
from auth.users u
where u.id = p.id
  and u.banned_until is not null
  and u.banned_until > now();

create table if not exists public.account_status_history (
  history_id bigint generated by default as identity primary key,
  user_id uuid not null,
  previous_status text not null check (previous_status in ('active', 'inactive')),
  new_status text not null check (new_status in ('active', 'inactive')),
  reason text not null,
  changed_by uuid not null,
  changed_at timestamptz not null default now()
);

create index if not exists account_status_history_user_idx
  on public.account_status_history(user_id, changed_at desc);

alter table public.medical_visits
  add column if not exists void_reason text,
  add column if not exists voided_at timestamptz,
  add column if not exists voided_by uuid references auth.users(id) on delete set null;

alter table public.medical_visits
  drop constraint if exists medical_visits_void_details_check;
alter table public.medical_visits
  add constraint medical_visits_void_details_check
  check (
    status <> 'voided'
    or (
      nullif(trim(void_reason), '') is not null
      and voided_at is not null
      and voided_by is not null
    )
  );

alter table public.medical_records
  add column if not exists lifecycle_status text not null default 'active',
  add column if not exists lifecycle_reason text,
  add column if not exists lifecycle_changed_at timestamptz,
  add column if not exists lifecycle_changed_by uuid references auth.users(id) on delete set null;

alter table public.medical_records
  drop constraint if exists medical_records_lifecycle_status_check;
alter table public.medical_records
  add constraint medical_records_lifecycle_status_check
