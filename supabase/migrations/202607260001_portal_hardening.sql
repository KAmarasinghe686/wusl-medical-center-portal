create or replace function public.notify_medical_record_change()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_student_user uuid;
begin
  if tg_op = 'UPDATE'
     and new.status is distinct from old.status
     and new.status in ('approved', 'rejected') then
    select s.user_id into v_student_user
    from public.students s
    where s.student_id = new.student_id;

    if v_student_user is not null then
      insert into public.notifications(user_id, title, message, type)
      values (
        v_student_user,
        'Medical record ' || initcap(new.status),
        'Your medical record REC-' || new.record_id || ' was ' || new.status || '.',
        'record_' || new.status
      );
    end if;
  end if;
  return new;
end;
$$;

drop trigger if exists notify_medical_record_change on public.medical_records;
create trigger notify_medical_record_change
  after update of status on public.medical_records
  for each row execute function public.notify_medical_record_change();

create or replace function public.replace_doctor_availability(p_schedule jsonb)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_doctor_id bigint;
  v_count integer;
begin
  if public.current_user_role() <> 'doctor' then
    raise exception 'Only doctors can manage availability' using errcode = '42501';
  end if;

  v_doctor_id := public.current_doctor_id();
  if v_doctor_id is null then
    raise exception 'Doctor profile not found' using errcode = 'P0002';
  end if;
  if jsonb_typeof(p_schedule) <> 'array' then
    raise exception 'Schedule must be an array' using errcode = '22023';
  end if;

  select count(*) into v_count
  from jsonb_to_recordset(p_schedule)
    as x(day text, available boolean, "startTime" text, "endTime" text);

  if v_count < 1 or v_count > 7 then
    raise exception 'Schedule must contain between one and seven days' using errcode = '22023';
  end if;

  if exists (
    select 1
    from jsonb_to_recordset(p_schedule)
      as x(day text, available boolean, "startTime" text, "endTime" text)
    where day not in ('Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday', 'Sunday')
      or "startTime" !~ '^\d{2}:\d{2}$'
      or "endTime" !~ '^\d{2}:\d{2}$'
      or (available and "startTime"::time >= "endTime"::time)
  ) then
    raise exception 'Schedule contains invalid days or time ranges' using errcode = '22023';
  end if;

  if exists (
    select day
    from jsonb_to_recordset(p_schedule)
      as x(day text, available boolean, "startTime" text, "endTime" text)
    group by day having count(*) > 1
  ) then
    raise exception 'Schedule contains duplicate days' using errcode = '22023';
  end if;

  delete from public.doctor_availability where doctor_id = v_doctor_id;
  insert into public.doctor_availability(doctor_id, day_of_week, start_time, end_time, is_available)
  select v_doctor_id, day, "startTime"::time, "endTime"::time, available
  from jsonb_to_recordset(p_schedule)
    as x(day text, available boolean, "startTime" text, "endTime" text);
end;
$$;

create or replace function public.review_medical_record(
  p_record_id bigint,
  p_expected_status text,
  p_new_status text,
  p_diagnosis text,
  p_observation_notes text,
  p_recommendation text,
  p_rejection_reason text,
  p_reversal_reason text
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_doctor_id bigint;
  v_record public.medical_records%rowtype;
begin
  if public.current_user_role() <> 'doctor' then
    raise exception 'Only doctors can review records' using errcode = '42501';
  end if;
  if p_new_status not in ('approved', 'rejected') then
    raise exception 'Invalid review status' using errcode = '22023';
  end if;

  v_doctor_id := public.current_doctor_id();
  select * into v_record
  from public.medical_records
  where record_id = p_record_id
  for update;

  if not found then
    raise exception 'Record not found' using errcode = 'P0002';
  end if;
  if v_record.status <> p_expected_status then
    raise exception 'Record was changed by another doctor' using errcode = '40001';
  end if;
  if v_record.status <> 'pending' and v_record.reviewed_by is distinct from v_doctor_id then
    raise exception 'Only the reviewing doctor can reverse this decision' using errcode = '42501';
  end if;
  if v_record.status <> 'pending' and nullif(trim(p_reversal_reason), '') is null then
    raise exception 'A reversal reason is required' using errcode = '22023';
  end if;
  if p_new_status = 'rejected' and nullif(trim(p_rejection_reason), '') is null then
    raise exception 'A rejection reason is required' using errcode = '22023';
  end if;

  update public.medical_records
  set status = p_new_status,
      reviewed_by = v_doctor_id,
      rejection_reason = case when p_new_status = 'rejected' then nullif(trim(p_rejection_reason), '') else null end,
      diagnosis = nullif(trim(p_diagnosis), ''),
      observation_notes = nullif(trim(p_observation_notes), ''),
      recommendation = nullif(trim(p_recommendation), '')
  where record_id = p_record_id;

  insert into public.medical_record_reviews(
    record_id, doctor_id, from_status, to_status, diagnosis,
    observation_notes, recommendation, rejection_reason, reversal_reason
  )
  values (
    p_record_id, v_doctor_id, v_record.status, p_new_status,
    nullif(trim(p_diagnosis), ''), nullif(trim(p_observation_notes), ''),
    nullif(trim(p_recommendation), ''), nullif(trim(p_rejection_reason), ''),
    nullif(trim(p_reversal_reason), '')
  );
end;
$$;

create or replace function public.admin_update_user_profile(
  p_actor_id uuid,
  p_user_id uuid,
  p_full_name text,
  p_role text,
  p_identifier text
)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if not exists (select 1 from public.profiles where id = p_actor_id and role = 'admin') then
    raise exception 'Administrator authorization required' using errcode = '42501';
  end if;
  if p_role not in ('student', 'doctor', 'worker', 'faculty', 'admin') then
    raise exception 'Invalid role' using errcode = '22023';
  end if;
  if nullif(trim(p_full_name), '') is null then
    raise exception 'Full name is required' using errcode = '22023';
  end if;
  if nullif(trim(p_identifier), '') is null then
    raise exception 'An index or employee ID is required for this role' using errcode = '22023';
  end if;

  update public.profiles
  set full_name = trim(p_full_name),
      role = p_role,
      employee_index = case when p_role in ('worker', 'faculty', 'doctor', 'admin') then trim(p_identifier) else null end
  where id = p_user_id;

  if not found then
    raise exception 'User profile not found' using errcode = 'P0002';
  end if;

  if p_role = 'doctor' then
    insert into public.doctors(user_id, full_name)
    values (p_user_id, trim(p_full_name))
    on conflict (user_id) do update set full_name = excluded.full_name;
  elsif p_role = 'student' then
    insert into public.students(user_id, full_name, index_no)
    values (p_user_id, trim(p_full_name), trim(p_identifier))
    on conflict (user_id) do update
      set full_name = excluded.full_name, index_no = excluded.index_no;
  end if;
end;
$$;

