create table if not exists public.advance_medical_notices (
  notice_id bigint generated by default as identity primary key,
  student_id bigint not null references public.students(student_id) on delete cascade,
  submission_type text not null default 'general' check (submission_type in ('general', 'exam')),
  illness_start_date date not null,
  expected_end_date date,
  reason text not null,
  treatment_status text default 'Resting at Home',
  hospital_name text,
  affected_courses jsonb,
  contact_number text,
  status text not null default 'pending' check (status in ('pending', 'acknowledged', 'medical_submitted')),
  acknowledged_by uuid references public.profiles(id) on delete set null,
  acknowledged_at timestamptz,
  faculty_notes text,
  created_at timestamptz not null default now()
);

