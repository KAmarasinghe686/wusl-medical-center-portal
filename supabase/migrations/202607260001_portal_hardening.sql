create table if not exists public.medical_record_reviews (
  review_id bigint generated by default as identity primary key,
  record_id bigint not null references public.medical_records(record_id) on delete cascade,
  doctor_id bigint not null references public.doctors(doctor_id) on delete restrict,
  from_status text not null check (from_status in ('pending', 'approved', 'rejected')),
  to_status text not null check (to_status in ('approved', 'rejected')),
  diagnosis text,
  observation_notes text,
  recommendation text,
  rejection_reason text,
  reversal_reason text,
  reviewed_at timestamptz not null default now()
);

