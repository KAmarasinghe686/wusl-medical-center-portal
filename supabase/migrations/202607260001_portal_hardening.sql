create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text,
  role text not null default 'unassigned',
  employee_index text unique,
  created_at timestamptz not null default now(),
  constraint profiles_role_check check (role in ('student', 'doctor', 'worker', 'faculty', 'admin', 'unassigned'))
);

create table if not exists public.students (
  student_id bigint generated by default as identity primary key,
  user_id uuid unique references auth.users(id) on delete set null,
  full_name text not null,
  index_no text not null unique,
  faculty text,
  academic_year text,
  dob date,
  gender text,
  contact_no text,
  created_at timestamptz not null default now()
);

create table if not exists public.doctors (
  doctor_id bigint generated by default as identity primary key,
  user_id uuid not null unique references auth.users(id) on delete cascade,
  full_name text not null,
  specialisation text,
  created_at timestamptz not null default now()
);

create table if not exists public.doctor_availability (
  availability_id bigint generated by default as identity primary key,
  doctor_id bigint not null references public.doctors(doctor_id) on delete cascade,
  day_of_week text not null,
  start_time time not null,
  end_time time not null,
  is_available boolean not null default false,
  constraint doctor_availability_day_check
    check (day_of_week in ('Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday', 'Sunday')),
  constraint doctor_availability_time_check check (start_time < end_time),
  constraint doctor_availability_unique_day unique (doctor_id, day_of_week)
);

create table if not exists public.medical_records (
  record_id bigint generated by default as identity primary key,
  student_id bigint not null references public.students(student_id) on delete restrict,
  purpose text not null,
  description text,
  issue_date date not null,
  status text not null default 'pending',
  submitted_by text not null default 'student',
  reviewed_by bigint references public.doctors(doctor_id) on delete set null,
  rejection_reason text,
  diagnosis text,
  observation_notes text,
  recommendation text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint medical_records_status_check check (status in ('pending', 'approved', 'rejected'))
);

alter table if exists public.medical_records
  add column if not exists diagnosis text,
  add column if not exists observation_notes text,
  add column if not exists recommendation text,
  add column if not exists updated_at timestamptz not null default now();

create table if not exists public.record_images (
  image_id bigint generated by default as identity primary key,
  record_id bigint not null references public.medical_records(record_id) on delete cascade,
  file_path text not null unique,
  file_type text not null,
  file_size_kb integer not null check (file_size_kb > 0 and file_size_kb <= 10240),
  created_at timestamptz not null default now()
);

create table if not exists public.medical_visits (
  visit_id bigint generated by default as identity primary key,
  doctor_id bigint not null references public.doctors(doctor_id) on delete restrict,
  user_id uuid not null references auth.users(id) on delete restrict,
  visit_date date not null,
  reason text not null,
  notes text,
  status text not null default 'completed',
  patient_name text not null,
  patient_index text not null,
  patient_type text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint medical_visits_patient_type_check check (patient_type in ('Student', 'Employee'))
);

alter table if exists public.medical_visits
  add column if not exists updated_at timestamptz not null default now();

create table if not exists public.notifications (
  notification_id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  title text not null,
  message text not null,
  type text not null default 'system',
  is_read boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists public.audit_logs (
  audit_id bigint generated by default as identity primary key,
  action text not null,
  table_name text not null,
  record_id text,
  user_id uuid,
  old_data jsonb,
  new_data jsonb,
  performed_at timestamptz not null default now()
