create or replace function public.audit_row_change()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_old jsonb;
  v_new jsonb;
  v_record_id text;
begin
  v_old := case when tg_op in ('UPDATE', 'DELETE') then to_jsonb(old) else null end;
  v_new := case when tg_op in ('INSERT', 'UPDATE') then to_jsonb(new) else null end;
  if auth.role() = 'service_role' then
    return coalesce(new, old);
  end if;
  v_record_id := coalesce(
    v_new ->> 'record_id', v_old ->> 'record_id',
    v_new ->> 'visit_id', v_old ->> 'visit_id',
    v_new ->> 'availability_id', v_old ->> 'availability_id'
  );

  insert into public.audit_logs(action, table_name, record_id, user_id, old_data, new_data)
  values (tg_op, tg_table_name, v_record_id, auth.uid(), v_old, v_new);

  return coalesce(new, old);
end;
$$;

